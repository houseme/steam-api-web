"""Check bilingual links, legal notices, reference coverage and the AWS-LC graph."""
import ast
import io
import json
from pathlib import Path
import re
import subprocess
import tokenize
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parent.parent
HAN = re.compile(r"[\u3400-\u9fff]")


def files():
    output = subprocess.check_output(["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z"], cwd=ROOT)
    return sorted({ROOT / name.decode() for name in output.split(b"\0") if name and (ROOT / name.decode()).is_file()})


def main():
    errors = []
    source_files = files()
    for path in source_files:
        relative = path.relative_to(ROOT)
        text = path.read_text(encoding="utf-8")
        body = text.split("\n", 1)[1] if text.startswith("#!") else text
        # Cargo may retain its generated banner ahead of repository notices.
        cargo_banner = ("# This file is automatically @generated by Cargo.\n"
                        "# It is not intended for manual editing.\n")
        if path.name == "Cargo.lock" and body.startswith(cargo_banner):
            body = body[len(cargo_banner):].lstrip("\n")
        prefix = "\n".join(body.splitlines()[:6])
        legal_start = ("// Copyright 2026 steam-api-web contributors.",
                       "# Copyright 2026 steam-api-web contributors.",
                       "<!--\nCopyright 2026 steam-api-web contributors.",
                       "Copyright 2026 steam-api-web contributors.")
        if path.suffix != ".json" and (not body.startswith(legal_start) or "SPDX-License-Identifier: Apache-2.0" not in prefix):
            errors.append(str(relative) + ": missing leading copyright/SPDX header")
        if path.suffix == ".json":
            data = json.loads(text)
            meta = data.get("_metadata", {})
            if next(iter(data), None) != "_metadata" or not meta.get("copyright") or meta.get("license") != "Apache-2.0":
                errors.append(str(relative) + ": JSON must start with legal _metadata")
        if path.suffix == ".py":
            comments = [t.string for t in tokenize.generate_tokens(io.StringIO(text).readline) if t.type == tokenize.COMMENT]
            tree = ast.parse(text)
            comments.extend(ast.get_docstring(n) or "" for n in ast.walk(tree) if isinstance(n, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)))
            if any(HAN.search(comment) for comment in comments):
                errors.append(str(relative) + ": code comments/docstrings must be English")
        if path.suffix == ".rs":
            if any(HAN.search(line) for line in text.splitlines() if re.match(r"\s*(//|/\*|\*)", line)):
                errors.append(str(relative) + ": Rust comments must be English")
        if path.suffix != ".md":
            continue
        peer = path.with_name(path.stem[:-3] + ".md") if path.stem.endswith("_ZH") else path.with_name(path.stem + "_ZH.md")
        if not peer.exists():
            errors.append(str(relative) + ": missing bilingual peer")
        if text.count("```") % 2:
            errors.append(str(relative) + ": unbalanced code fences")
        for target in re.findall(r"!?\[[^\]]*\]\(([^)]+)\)", text):
            target = target.strip("<>")
            parsed = urlsplit(target)
            if parsed.scheme or not parsed.path:
                continue
            if not (path.parent / unquote(parsed.path)).exists():
                errors.append(str(relative) + ": missing link target " + target)
        in_code = False
        for line in text.splitlines():
            if line.startswith("```"):
                in_code = not in_code
            elif in_code and HAN.search(line) and re.match(r"\s*(//|#)", line):
                errors.append(str(relative) + ": code example comments must be English")
    inventory = json.loads((ROOT / "docs/api-inventory.json").read_text(encoding="utf-8"))
    interfaces = inventory["interfaces"]
    if len(interfaces) != 33 or len({i["interface"] for i in interfaces}) != 33:
        errors.append("reference inventory must cover all 33 reviewed interfaces")
    explicit = sum(1 for i in interfaces for m in i["methods"] if not m.get("inherited_from"))
    if explicit != inventory["_metadata"]["explicit_signatures"]:
        errors.append("documented signature total does not match inventory metadata")
    for language in ("", "_ZH"):
        roadmap = (ROOT / ("docs/roadmap" + language + ".md")).read_text(encoding="utf-8")
        for interface in interfaces:
            if interface["interface"] not in roadmap:
                errors.append("roadmap missing interface " + interface["interface"])
        for module in inventory["_metadata"]["sdk_reference"]["source_modules"]:
            if module[4:] not in roadmap:
                errors.append("roadmap missing SDK module " + module)
    graph = subprocess.check_output(["cargo", "tree", "--locked", "--edges", "normal", "--prefix", "none"], cwd=ROOT, text=True)
    if "aws-lc-rs v" not in graph or re.search(r"^(ring|native-tls) v", graph, re.M):
        errors.append("normal TLS graph must use AWS-LC without ring/native-tls")
    if errors:
        raise SystemExit("\n".join(errors))
    print("Repository checks passed: legal headers, bilingual links, 33 interfaces, SDK modules and AWS-LC graph")


if __name__ == "__main__":
    main()
